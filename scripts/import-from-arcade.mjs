// scripts/import-from-arcade.mjs
// Rebuilds this package's len×tier grid from a new base (in .context/import) plus the
// current enriched entries (re-tiered under the new band). Reusable across increments.
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { bucketByLength, bucketByTier } from './regrid-lib.mjs';
import { parseWords, freqTierForRank, retierEntry, readEnrichedFull } from './import-lib.mjs';

const BAND = Number(process.env.CW_BAND ?? 18000);
const DATA = join('src', 'data');
const IMPORT = join('.context', 'import');
const langs = ['en', 'de'];
const TIERS = [1, 2, 3, 4, 5];

function baseWordsByTier(lang) {
  // returns { ordered: string[] (rank order), byTier: Map<tier, string[]> }
  const ordered = [];
  const byTier = new Map();
  for (const tier of TIERS) {
    const words = parseWords(readFileSync(join(IMPORT, 'base', lang, `tier-${tier}.ts`), 'utf8'));
    byTier.set(tier, words);
    ordered.push(...words);
  }
  return { ordered, byTier };
}

function emitBase(lang, len, tier, words) {
  const dir = join(DATA, lang, 'base', `len-${len}`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, `tier-${tier}.ts`),
    `// Generated by scripts/import-from-arcade.mjs — do not edit by hand.\n` +
      `// ${lang} base words, length ${len}, freqTier ${tier} (frequency order preserved).\n` +
      `export const WORDS: readonly string[] = [\n${words.map((w) => `  ${JSON.stringify(w)},`).join('\n')}\n];\n`,
  );
}

function emitEnriched(lang, len, tier, entries) {
  const dir = join(DATA, lang, 'enriched', `len-${len}`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, `tier-${tier}.ts`),
    `// Generated by scripts/import-from-arcade.mjs — do not edit by hand.\n` +
      `import type { EnrichedEntry } from '../../../../types.js';\n\n` +
      `export const ENTRIES: readonly EnrichedEntry[] = ${JSON.stringify(entries, null, 2)};\n`,
  );
}

for (const lang of langs) {
  // --- BASE: replace the grid from the new 90k tiers ---
  const { ordered, byTier } = baseWordsByTier(lang);
  const rankMap = new Map(ordered.map((w, i) => [w, i]));
  rmSync(join(DATA, lang, 'base'), { recursive: true, force: true });
  for (const tier of TIERS) {
    for (const [len, words] of bucketByLength(byTier.get(tier))) emitBase(lang, len, tier, words);
  }

  // --- ENRICHED: re-tier the current entries from the arcade JSON dump, rewrite the grid ---
  const ENTRIES = readEnrichedFull(readFileSync(join(IMPORT, `enriched-full-${lang}.json`), 'utf8'));
  const retiered = ENTRIES.map((e) => retierEntry(e, rankMap, BAND));
  rmSync(join(DATA, lang, 'enriched'), { recursive: true, force: true });
  const lenGroups = new Map();
  for (const e of retiered) {
    if (!lenGroups.has(e.length)) lenGroups.set(e.length, []);
    lenGroups.get(e.length).push(e);
  }
  for (const [len, entries] of lenGroups) {
    for (const [tier, group] of bucketByTier(entries)) emitEnriched(lang, len, tier, group);
  }
}
console.log('Imported 90k base + re-tiered enriched into the grid.');
